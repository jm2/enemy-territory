#!/usr/bin/env python3
"""Generate legacy/static/rename_<module>.h for one-binary static modules.

Each ET: Legacy module was its own shared library, so cgame, ui, qagame and the
engine all define Com_Printf, Q_stricmp, BG_*, q_math and so on, with different
headers behind them. Linking them into one application needs every module
global to have a name of its own. This compiles each module with the host
compiler, reads its defined globals from nm, and writes a -include header that
gives each one a module prefix. nm and macros need no object-format support, so
the same header works for ELF hosts and Retro68's XCOFF.

Re-run after scripts/sync_legacy.sh. --check fails if the headers are stale.
"""
import concurrent.futures, os, re, subprocess, sys, tempfile
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATIC = os.path.join(ROOT, 'legacy', 'static')
PREFIX = {'cgame': 'etcg_', 'ui': 'etui_', 'qagame': 'etqa_'}

def lines(name):
    with open(os.path.join(STATIC, name)) as f:
        return [l.strip() for l in f if l.strip() and not l.startswith('#')]

def compile_one(job):
    module, src, flags, out = job
    obj = os.path.join(out, module + '.' + src.replace('/', '_') + '.o')
    r = subprocess.run(['cc'] + flags + ['-c', os.path.join(ROOT, 'legacy', src), '-o', obj],
                       stderr=subprocess.PIPE, text=True, errors='replace')
    if r.returncode:
        sys.exit('%s: %s\n%s' % (module, src, r.stderr[-1500:]))
    return obj

def symbols(objs):
    r = subprocess.run(['nm', '-g', '--defined-only', '-f', 'posix'] + objs, stdout=subprocess.PIPE, text=True, check=True)
    names = set()
    for l in r.stdout.splitlines():
        parts = l.split()
        if len(parts) >= 2 and len(parts[1]) == 1 and parts[1] in 'TDBRVWGSC':
            names.add(parts[0])
    return sorted(names)

def main():
    check = '--check' in sys.argv
    work = tempfile.mkdtemp(prefix='et-renames.', dir=os.environ.get('TMPDIR', '/var/tmp'))
    base = ['-m32', '-std=gnu11', '-fgnu89-inline', '-fsigned-char', '-w', '-O0', '-fno-common', '-fno-pic', '-I' + STATIC,
            '-I' + os.path.join(ROOT, 'legacy', 'vendor', 'cjson'),
            '-I' + os.path.join(ROOT, 'legacy', 'src', 'qcommon', 'json'), '-DBUNDLED_CJSON']
    base += ['-D' + d for d in lines('common.defines')]
    stale = []
    for module, prefix in PREFIX.items():
        flags = base + ['-D' + d for d in lines(module + '.defines')]
        jobs = [(module, s, flags, work) for s in lines(module + '.sources')]
        with concurrent.futures.ThreadPoolExecutor(os.cpu_count()) as pool:
            objs = list(pool.map(compile_one, jobs))
        names = symbols(objs)
        text = '/* Generated by scripts/gen_static_renames.py. Do not edit. */\n'
        text += ''.join('#define %s %s%s\n' % (n, prefix, n) for n in names)
        path = os.path.join(STATIC, 'rename_%s.h' % module)
        if check:
            if not os.path.exists(path) or open(path).read() != text:
                stale.append(path)
        else:
            with open(path, 'w') as f:
                f.write(text)
        print(module, len(names), 'globals')
    subprocess.call(['rm', '-rf', work])
    if stale:
        sys.exit('stale: ' + ' '.join(stale))

if __name__ == '__main__':
    main()
